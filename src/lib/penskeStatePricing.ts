export const PENSKE_STATE_PRICING: Record<string, PenskeStateRates> = Object.fromEntries(
  Object.entries(RAW).map(([state, r]) => [
    state,
    {
      base: { '12': r.base['12'], '16': r.base['16'], '22': r.base['26'], '26': r.base['26'] },
      perMile: { '12': r.perMile['12'], '16': r.perMile['16'], '22': r.perMile['26'], '26': r.perMile['26'] },
    },
  ]),
);

export function getPenskeStateRates(state: string | undefined | null): PenskeStateRates {
  if (!state) return NATIONAL_AVG;
  const key = state.trim().toUpperCase();
  return PENSKE_STATE_PRICING[key] ?? NATIONAL_AVG;
}

export function estimatePenskeDailyRental(
  miles: number,
  size: TruckSize,
  days: number,
  fromState: string,
  isLocalMove: boolean,
): { base: number; mileage: number; total: number; rates: PenskeStateRates } {
  const rates = getPenskeStateRates(fromState);
  const effectiveDays = Math.max(1, Math.round(days));
  const effectiveMiles = isLocalMove ? Math.max(miles * 2, 20) : Math.max(miles, 0);
  const baseCost = rates.base[size] * effectiveDays;
  const mileageCost = rates.perMile[size] * effectiveMiles;
  return {
    base: Math.round(baseCost),
    mileage: Math.round(mileageCost),
    total: Math.round(baseCost + mileageCost),
    rates,
  };
}
